function buildUnits(seeds: UnitSeed[]): CurriculumUnit[] {
  return seeds.map((seed, unitIndex) => ({
    ...seed,
    order: unitIndex + 1,
    lessons: seed.lessons.map((lessonSeed, lessonIndex) => ({
      ...lessonSeed,
      unitId: seed.id,
      level: seed.level,
      order: lessonIndex + 1,
    })),
  }));
}

export const CURRICULUM_UNITS: CurriculumUnit[] = buildUnits(UNIT_SEEDS);

export const CURRICULUM_LESSONS: CurriculumLesson[] = CURRICULUM_UNITS.flatMap(
  (unit) => unit.lessons,
);

export const CURRICULUM_LEVELS: CefrLevel[] = ["A1", "A2", "B1"];
